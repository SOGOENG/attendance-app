/* =========================================
   tool_catalog
========================================= */

create table if not exists public.tool_catalog (
  id bigint generated by default as identity primary key,

  tool_group text not null
    check (
      tool_group <> ''
      and tool_group = btrim(tool_group)
    ),

  tool_name text not null
    check (
      tool_name <> ''
      and tool_name = btrim(tool_name)
    ),

  code_prefix text not null
    check (
      code_prefix ~
      '^[A-Za-z0-9]+(-[A-Za-z0-9]+)*$'
    ),

  inspection_required boolean
    not null
    default true,

  inspection_category text null
    check (
      inspection_category in (
        '3p',
        'double_insulated',
        'battery',
        'cord_reel',
        'ac_welder',
        'dc_welder'
      )
    ),

  active boolean
    not null
    default true,

  sort_order integer
    not null
    default 0,

  created_at timestamptz
    not null
    default now(),

  updated_at timestamptz
    not null
    default now(),

  unique (
    tool_group,
    tool_name
  )
);


/* =========================================
   旧ドラフト制約除去
========================================= */

alter table public.tool_catalog
  drop constraint
  if exists tool_catalog_check;


/* =========================================
   RLS
========================================= */

alter table public.tool_catalog
  enable row level security;


revoke all
on public.tool_catalog
from public, anon, authenticated;


grant
  select,
  insert,
  update
on public.tool_catalog
to authenticated;


grant
  usage,
  select
on sequence public.tool_catalog_id_seq
to authenticated;


/* =========================================
   SELECT
========================================= */

drop policy
if exists tool_catalog_read
on public.tool_catalog;


create policy tool_catalog_read
on public.tool_catalog
for select
to authenticated
using (true);


/* =========================================
   INSERT
========================================= */

drop policy
if exists tool_catalog_insert
on public.tool_catalog;


create policy tool_catalog_insert
on public.tool_catalog
for insert
to authenticated
with check (
  public.is_tool_registration_admin()
);


/* =========================================
   UPDATE
========================================= */

drop policy
if exists tool_catalog_update
on public.tool_catalog;


create policy tool_catalog_update
on public.tool_catalog
for update
to authenticated
using (
  public.is_tool_registration_admin()
)
with check (
  public.is_tool_registration_admin()
);


/* =========================================
   updated_at
========================================= */

create or replace function
public.touch_tool_catalog()
returns trigger
language plpgsql
set search_path = ''
as $$
begin

  new.updated_at := now();

  return new;

end;
$$;


revoke all
on function public.touch_tool_catalog()
from public, anon, authenticated;


drop trigger
if exists tool_catalog_updated
on public.tool_catalog;


create trigger tool_catalog_updated
before update
on public.tool_catalog
for each row
execute function public.touch_tool_catalog();


