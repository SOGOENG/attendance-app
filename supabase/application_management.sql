create or replace function public.current_employee_id()
returns bigint
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select e.id
  from public.employees e
  where e.auth_user_id = auth.uid()
    and e.active = true
  limit 1
$$;

create or replace function public.is_application_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.employees e
    where e.auth_user_id = auth.uid()
      and e.active = true
      and e.admin_scope = 'all'
  )
$$;

create or replace function public.set_application_updated_at()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  new.updated_at := now();
  return new;
