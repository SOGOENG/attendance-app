create table if not exists public.application_types (
  code text primary key,
  display_name text not null,
  category text not null,
  detail_kind text not null unique,
  active boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (code ~ '^[a-z][a-z0-9_]*$')
);

insert into public.application_types
  (code, display_name, category, detail_kind, display_order)
values
  ('paid_leave', '有給休暇申請', 'leave', 'paid_leave', 10),
  ('comp_leave', '代替休日申請', 'leave', 'comp_leave', 20)
on conflict (code) do update set
  display_name = excluded.display_name,
  category = excluded.category,
  detail_kind = excluded.detail_kind,
  display_order = excluded.display_order;

create table if not exists public.applications (
  id bigint generated by default as identity primary key,
  application_type text not null references public.application_types(code),
  employee_id bigint not null references public.employees(id),
  status text not null default 'draft'
    check (status in (
      'draft', 'submitted', 'approved', 'rejected',
      'revision_required', 'cancelled'
    )),
  submitted_at timestamptz,
  approved_at timestamptz,
  approved_by_employee_id bigint references public.employees(id),
  rejected_at timestamptz,
  rejected_by_employee_id bigint references public.employees(id),
  reviewer_comment text,
  applicant_note text,
  created_by_employee_id bigint not null references public.employees(id),
  updated_by_employee_id bigint references public.employees(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    status <> 'approved'
    or (approved_at is not null and approved_by_employee_id is not null)
  ),
  check (
    status <> 'rejected'
    or (rejected_at is not null and rejected_by_employee_id is not null)
  )
);

create table if not exists public.application_status_history (
  id bigint generated by default as identity primary key,
  application_id bigint not null
    references public.applications(id) on delete cascade,
  from_status text,
  to_status text not null,
  comment text,
  changed_by_employee_id bigint not null references public.employees(id),
  changed_at timestamptz not null default now()
);

create table if not exists public.paid_leave_application_details (
  application_id bigint primary key
    references public.applications(id) on delete cascade,
  site_id bigint references public.sites(id) on delete set null,
  start_date date not null,
  end_date date not null,
  days numeric(6,2) not null,
  day_part text not null default 'full'
    check (day_part in ('full', 'am', 'pm', 'custom')),
  reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint paid_leave_date_order_check check (end_date >= start_date),
  constraint paid_leave_same_fiscal_year_check check (
    extract(year from start_date)::integer
      - case when extract(month from start_date) < 4 then 1 else 0 end
    =
    extract(year from end_date)::integer
      - case when extract(month from end_date) < 4 then 1 else 0 end
  ),
  constraint paid_leave_days_positive_check check (days > 0),
  constraint paid_leave_day_part_days_check check (
    (day_part in ('am', 'pm') and start_date = end_date and days = 0.5)
    or (day_part = 'full' and days >= 1 and days <= (end_date - start_date + 1))
    or (day_part = 'custom' and days <= (end_date - start_date + 1))
  )
);

create table if not exists public.comp_leave_application_details (
  application_id bigint primary key
    references public.applications(id) on delete cascade,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.comp_leave_dates (
  id bigint generated by default as identity primary key,
  application_id bigint not null
    references public.comp_leave_application_details(application_id)
    on delete cascade,
  leave_date date not null,
  days numeric(6,2) not null
    check (days in (0.5, 1.0)),
  display_order integer not null default 0 check (display_order >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (application_id, leave_date)
);

create table if not exists public.paid_leave_balances (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id),
  fiscal_year integer not null check (fiscal_year between 2000 and 2200),
  granted_days numeric(7,2) not null default 0 check (granted_days >= 0),
  carried_days numeric(7,2) not null default 0 check (carried_days >= 0),
  imported_used_days numeric(7,2) not null default 0 check (imported_used_days >= 0),
  adjustment_days numeric(7,2) not null default 0,
  used_days numeric(7,2) not null default 0 check (used_days >= 0),
  remaining_days numeric(7,2) not null default 0,
  base_date date,
  created_by_employee_id bigint references public.employees(id),
  updated_by_employee_id bigint references public.employees(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (employee_id, fiscal_year)
);

create table if not exists public.paid_leave_balance_transactions (
  id bigint generated by default as identity primary key,
  balance_id bigint not null
    references public.paid_leave_balances(id) on delete cascade,
  application_id bigint references public.applications(id),
  transaction_type text not null
    check (transaction_type in (
      'grant', 'carryover', 'imported_usage',
      'application_usage', 'adjustment'
    )),
  days numeric(7,2) not null,
  source_key text not null,
  active boolean not null default true,
  reason text,
  created_by_employee_id bigint references public.employees(id),
  created_at timestamptz not null default now(),
  unique (balance_id, source_key),
  check (
    (transaction_type in ('grant', 'carryover') and days >= 0)
    or (transaction_type in ('imported_usage', 'application_usage') and days <= 0)
    or transaction_type = 'adjustment'
  )
);

create unique index if not exists paid_leave_application_usage_uidx
  on public.paid_leave_balance_transactions (application_id)
  where transaction_type = 'application_usage';

create table if not exists public.holiday_work_records (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id),
  work_date date not null,
  earned_days numeric(6,2) not null check (earned_days > 0),
  used_days numeric(6,2) not null default 0 check (used_days >= 0),
  remaining_days numeric(6,2) not null check (remaining_days >= 0),
  site_id bigint references public.sites(id) on delete set null,
  note text,
  status text not null default 'active'
    check (status in ('active', 'cancelled')),
  source_type text not null default 'manual'
    check (source_type in ('manual', 'attendance', 'import')),
  source_attendance_id bigint
    references public.attendance(id) on delete set null,
  created_by_employee_id bigint not null references public.employees(id),
  updated_by_employee_id bigint references public.employees(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (used_days <= earned_days),
  check (remaining_days = earned_days - used_days)
);

create unique index if not exists holiday_work_attendance_source_uidx
  on public.holiday_work_records (source_attendance_id)
  where source_attendance_id is not null and status = 'active';

create table if not exists public.comp_leave_allocations (
  id bigint generated by default as identity primary key,
  application_id bigint not null
    references public.comp_leave_application_details(application_id)
    on delete cascade,
  holiday_work_record_id bigint not null
    references public.holiday_work_records(id),
  allocated_days numeric(6,2) not null check (allocated_days > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (application_id, holiday_work_record_id)
);

