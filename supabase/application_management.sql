create or replace function public.recalculate_paid_leave_balance(p_balance_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_balance public.paid_leave_balances%rowtype;
  v_granted numeric(7,2);
  v_carried numeric(7,2);
  v_imported_used numeric(7,2);
  v_application_used numeric(7,2);
  v_adjustment numeric(7,2);
  v_remaining numeric(7,2);
begin
  select * into v_balance
  from public.paid_leave_balances
  where id = p_balance_id
  for update;

  if not found then raise exception 'paid_leave_balance_not_found'; end if;

  select
    coalesce(sum(days) filter (where transaction_type = 'grant' and active), 0),
    coalesce(sum(days) filter (where transaction_type = 'carryover' and active), 0),
    coalesce(-sum(days) filter (where transaction_type = 'imported_usage' and active), 0),
    coalesce(-sum(days) filter (where transaction_type = 'application_usage' and active), 0),
    coalesce(sum(days) filter (where transaction_type = 'adjustment' and active), 0),
    coalesce(sum(days) filter (where active), 0)
  into v_granted, v_carried, v_imported_used,
       v_application_used, v_adjustment, v_remaining
  from public.paid_leave_balance_transactions
  where balance_id = p_balance_id;

  if v_remaining < 0 then raise exception 'insufficient_paid_leave_balance'; end if;

  update public.paid_leave_balances
  set granted_days = v_granted,
      carried_days = v_carried,
      imported_used_days = v_imported_used,
      adjustment_days = v_adjustment,
      used_days = v_imported_used + v_application_used,
      remaining_days = v_remaining,
      updated_by_employee_id = public.current_employee_id()
  where id = p_balance_id;
end;
$$;

create or replace function public.recalculate_holiday_work_record(p_record_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_record public.holiday_work_records%rowtype;
  v_used numeric(6,2);
begin
  select * into v_record
  from public.holiday_work_records
  where id = p_record_id
  for update;

  if not found then raise exception 'holiday_work_record_not_found'; end if;

  select coalesce(sum(ca.allocated_days), 0)
  into v_used
  from public.comp_leave_allocations ca
  join public.applications a on a.id = ca.application_id
  where ca.holiday_work_record_id = p_record_id
    and a.status = 'approved';

  if v_used > v_record.earned_days then
    raise exception 'insufficient_comp_leave_balance';
  end if;

  update public.holiday_work_records
  set used_days = v_used,
      remaining_days = earned_days - v_used,
      updated_by_employee_id = public.current_employee_id()
  where id = p_record_id;
end;
$$;

create or replace function public.validate_paid_leave_application(p_application_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_detail public.paid_leave_application_details%rowtype;
  v_start_fiscal_year integer;
  v_end_fiscal_year integer;
  v_calendar_days integer;
begin
  select * into v_detail
  from public.paid_leave_application_details
  where application_id = p_application_id;
  if not found then raise exception 'paid_leave_detail_required'; end if;

  if v_detail.end_date < v_detail.start_date then
    raise exception 'paid_leave_end_date_before_start_date';
  end if;

  v_start_fiscal_year := extract(year from v_detail.start_date)::integer
    - case when extract(month from v_detail.start_date) < 4 then 1 else 0 end;
  v_end_fiscal_year := extract(year from v_detail.end_date)::integer
    - case when extract(month from v_detail.end_date) < 4 then 1 else 0 end;
  if v_start_fiscal_year <> v_end_fiscal_year then
    raise exception 'paid_leave_cross_fiscal_year_not_allowed';
  end if;

  v_calendar_days := v_detail.end_date - v_detail.start_date + 1;
  if v_detail.days <= 0 then raise exception 'paid_leave_days_must_be_positive'; end if;
  if v_detail.day_part in ('am', 'pm')
     and (v_detail.start_date <> v_detail.end_date or v_detail.days <> 0.5) then
    raise exception 'paid_leave_half_day_must_be_0_5';
  end if;
  if v_detail.day_part = 'full' and v_detail.days < 1 then
    raise exception 'paid_leave_full_day_must_be_at_least_1';
  end if;
  if v_detail.days > v_calendar_days then
    raise exception 'paid_leave_days_exceed_calendar_range';
  end if;
end;
$$;

