$$;

create or replace function public.set_application_actor()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'INSERT' then
    new.created_by_employee_id := public.current_employee_id();
    new.employee_id := public.current_employee_id();
