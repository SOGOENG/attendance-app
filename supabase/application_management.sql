create or replace function public.submit_application(p_application_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_app public.applications%rowtype;
  v_leave_days numeric(6,2);
  v_allocated_days numeric(6,2);
begin
  select * into v_app from public.applications
  where id = p_application_id for update;

  if not found then raise exception 'application_not_found'; end if;
  if v_app.employee_id <> public.current_employee_id() then raise exception 'forbidden'; end if;
  if v_app.status <> 'draft' then raise exception 'application_not_draft'; end if;

  if v_app.application_type = 'paid_leave' then
    perform public.validate_paid_leave_application(v_app.id);
  elsif v_app.application_type = 'comp_leave' then
    if not exists (select 1 from public.comp_leave_application_details
      where application_id = v_app.id) then
      raise exception 'comp_leave_detail_required';
    end if;
    select coalesce(sum(days), 0) into v_leave_days
    from public.comp_leave_dates where application_id = v_app.id;
    if v_leave_days <= 0 then raise exception 'comp_leave_date_required'; end if;
    select coalesce(sum(allocated_days), 0) into v_allocated_days
    from public.comp_leave_allocations where application_id = v_app.id;
    if v_allocated_days <> v_leave_days then
      raise exception 'comp_leave_allocation_mismatch';
    end if;
  else
    raise exception 'unsupported_application_type';
  end if;

  update public.applications
  set status = 'submitted', submitted_at = now()
  where id = v_app.id;

  insert into public.application_status_history
    (application_id, from_status, to_status, changed_by_employee_id)
  values (v_app.id, v_app.status, 'submitted', public.current_employee_id());
end;
$$;

create or replace function public.reopen_application_draft(p_application_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare v_app public.applications%rowtype;
begin
  select * into v_app from public.applications
  where id = p_application_id for update;
  if not found then raise exception 'application_not_found'; end if;
  if v_app.employee_id <> public.current_employee_id() then raise exception 'forbidden'; end if;
  if v_app.status <> 'revision_required' then raise exception 'application_not_revision_required'; end if;

  update public.applications set status = 'draft' where id = v_app.id;
  insert into public.application_status_history
    (application_id, from_status, to_status, changed_by_employee_id)
  values (v_app.id, v_app.status, 'draft', public.current_employee_id());
end;
$$;

create or replace function public.delete_draft_application(p_application_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_app public.applications%rowtype;
  v_actor bigint;
begin
  v_actor := public.current_employee_id();
  if v_actor is null then raise exception 'employee_not_found'; end if;

  select * into v_app
  from public.applications
  where id = p_application_id
  for update;

  if not found then raise exception 'application_not_found'; end if;
  if v_app.employee_id <> v_actor then
    raise exception 'draft_application_owner_required';
  end if;
  if v_app.status <> 'draft' then raise exception 'application_not_draft'; end if;

  -- 詳細・代休日・割当・状態履歴は既存FKのON DELETE CASCADEで削除します。
  delete from public.applications where id = v_app.id;
end;
$$;

create or replace function public.review_application(
  p_application_id bigint,
  p_decision text,
  p_comment text default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_app public.applications%rowtype;
  v_admin bigint;
  v_detail public.paid_leave_application_details%rowtype;
  v_fiscal_year integer;
  v_balance_id bigint;
  v_record_id bigint;
  v_leave_days numeric(6,2);
  v_allocated_days numeric(6,2);
begin
  if not public.is_application_admin() then raise exception 'admin_required'; end if;
  if p_decision not in ('approved', 'rejected', 'revision_required') then
    raise exception 'invalid_decision';
  end if;

  v_admin := public.current_employee_id();
  select * into v_app from public.applications
  where id = p_application_id for update;
  if not found then raise exception 'application_not_found'; end if;
  if v_app.status <> 'submitted' then raise exception 'application_not_submitted'; end if;

  if p_decision = 'approved' and v_app.application_type = 'paid_leave' then
    perform public.validate_paid_leave_application(v_app.id);
    select * into v_detail from public.paid_leave_application_details
    where application_id = v_app.id;
    if not found then raise exception 'paid_leave_detail_required'; end if;

    v_fiscal_year := extract(year from v_detail.start_date)::integer
      - case when extract(month from v_detail.start_date) < 4 then 1 else 0 end;

    select id into v_balance_id from public.paid_leave_balances
    where employee_id = v_app.employee_id and fiscal_year = v_fiscal_year
    for update;
    if not found then raise exception 'paid_leave_balance_not_found'; end if;

    -- base_date以前（同日を含む）の使用実績は経理取込済み使用日数に
    -- 含まれるため、Staff Portal側で再承認して二重計上させません。
    if exists (
      select 1
      from public.paid_leave_balances b
      where b.id = v_balance_id
        and b.base_date is not null
        and v_detail.start_date <= b.base_date
    ) then
      raise exception 'paid_leave_date_already_in_imported_period';
    end if;

    insert into public.paid_leave_balance_transactions
      (balance_id, application_id, transaction_type, days, source_key,
       created_by_employee_id)
    values
      (v_balance_id, v_app.id, 'application_usage', -v_detail.days,
       'application:' || v_app.id::text, v_admin)
    on conflict (balance_id, source_key) do update
      set days = excluded.days, active = true;
  end if;

  if p_decision = 'approved' and v_app.application_type = 'comp_leave' then
    select coalesce(sum(days), 0) into v_leave_days
    from public.comp_leave_dates where application_id = v_app.id;
    select coalesce(sum(allocated_days), 0) into v_allocated_days
    from public.comp_leave_allocations where application_id = v_app.id;
    if v_leave_days <= 0 then raise exception 'comp_leave_date_required'; end if;
    if v_leave_days <> v_allocated_days then raise exception 'comp_leave_allocation_mismatch'; end if;
    if exists (
      select 1
      from public.comp_leave_allocations ca
      left join public.holiday_work_records h
        on h.id = ca.holiday_work_record_id
       and h.employee_id = v_app.employee_id
       and h.status = 'active'
      where ca.application_id = v_app.id and h.id is null
    ) then raise exception 'invalid_or_cancelled_holiday_work_record'; end if;
    -- デッドロック防止のためID順でロックします。
    for v_record_id in
      select h.id
      from public.holiday_work_records h
      join public.comp_leave_allocations ca on ca.holiday_work_record_id = h.id
      where ca.application_id = v_app.id
        and h.employee_id = v_app.employee_id
        and h.status = 'active'
      order by h.id
      for update of h
    loop
      null;
    end loop;
    if not exists (select 1 from public.comp_leave_allocations where application_id = v_app.id)
    then raise exception 'comp_leave_allocation_required'; end if;
  end if;

  update public.applications
  set status = p_decision,
      reviewer_comment = nullif(trim(p_comment), ''),
      approved_at = case when p_decision = 'approved' then now() else null end,
      approved_by_employee_id = case when p_decision = 'approved' then v_admin else null end,
      rejected_at = case when p_decision = 'rejected' then now() else null end,
      rejected_by_employee_id = case when p_decision = 'rejected' then v_admin else null end
  where id = v_app.id;

  if p_decision = 'approved' and v_app.application_type = 'paid_leave' then
    perform public.recalculate_paid_leave_balance(v_balance_id);
  elsif p_decision = 'approved' and v_app.application_type = 'comp_leave' then
    for v_record_id in select holiday_work_record_id from public.comp_leave_allocations
      where application_id = v_app.id order by holiday_work_record_id
    loop
      perform public.recalculate_holiday_work_record(v_record_id);
    end loop;
  end if;

  insert into public.application_status_history
    (application_id, from_status, to_status, comment, changed_by_employee_id)
  values (v_app.id, v_app.status, p_decision, nullif(trim(p_comment), ''), v_admin);
end;
$$;

create or replace function public.cancel_application(
  p_application_id bigint,
  p_comment text default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_app public.applications%rowtype;
  v_actor bigint;
  v_balance_id bigint;
  v_record_id bigint;
begin
  v_actor := public.current_employee_id();
  select * into v_app from public.applications
  where id = p_application_id for update;
  if not found then raise exception 'application_not_found'; end if;

  if v_app.status = 'cancelled' then return; end if;
  if not public.is_application_admin() then
    if v_app.employee_id <> v_actor then raise exception 'forbidden'; end if;
    if v_app.status not in ('draft', 'submitted', 'revision_required') then
      raise exception 'admin_required_to_cancel_approved_application';
    end if;
  end if;

  if v_app.status = 'approved' and v_app.application_type = 'paid_leave' then
    select balance_id into v_balance_id
    from public.paid_leave_balance_transactions
    where application_id = v_app.id and transaction_type = 'application_usage'
    for update;
    update public.paid_leave_balance_transactions
      set active = false
      where application_id = v_app.id and transaction_type = 'application_usage';
  elsif v_app.status = 'approved' and v_app.application_type = 'comp_leave' then
    perform 1 from public.holiday_work_records h
    where h.id in (select holiday_work_record_id from public.comp_leave_allocations
      where application_id = v_app.id)
    order by h.id for update;
  end if;

  update public.applications
  set status = 'cancelled', reviewer_comment = coalesce(nullif(trim(p_comment), ''), reviewer_comment),
      approved_at = null, approved_by_employee_id = null,
      rejected_at = null, rejected_by_employee_id = null
  where id = v_app.id;

  if v_balance_id is not null then
    perform public.recalculate_paid_leave_balance(v_balance_id);
  end if;
  if v_app.status = 'approved' and v_app.application_type = 'comp_leave' then
    for v_record_id in select holiday_work_record_id from public.comp_leave_allocations
      where application_id = v_app.id order by holiday_work_record_id
    loop
      perform public.recalculate_holiday_work_record(v_record_id);
    end loop;
  end if;

  insert into public.application_status_history
    (application_id, from_status, to_status, comment, changed_by_employee_id)
  values (v_app.id, v_app.status, 'cancelled', nullif(trim(p_comment), ''), v_actor);
end;
$$;

