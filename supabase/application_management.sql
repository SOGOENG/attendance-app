create or replace function public.update_holiday_work(
  p_record_id bigint,
  p_work_date date,
  p_earned_days numeric,
  p_site_id bigint default null,
  p_note text default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_record public.holiday_work_records%rowtype;
  v_approved_used numeric(6,2);
  v_committed_allocated numeric(6,2);
begin
  if not public.is_application_admin() then raise exception 'admin_required'; end if;
  if p_earned_days <= 0 then raise exception 'invalid_earned_days'; end if;

  select * into v_record from public.holiday_work_records
  where id = p_record_id for update;
  if not found then raise exception 'holiday_work_record_not_found'; end if;
  if v_record.status = 'cancelled' then raise exception 'holiday_work_record_already_cancelled'; end if;

  select
    coalesce(sum(ca.allocated_days) filter (where a.status = 'approved'), 0),
    coalesce(sum(ca.allocated_days) filter (where a.status in ('submitted', 'approved')), 0)
  into v_approved_used, v_committed_allocated
  from public.comp_leave_allocations ca
  join public.applications a on a.id = ca.application_id
  where ca.holiday_work_record_id = p_record_id;

  if p_earned_days < v_committed_allocated then
    raise exception 'earned_days_cannot_be_less_than_submitted_or_approved_comp_leave_allocation';
  end if;

  update public.holiday_work_records
  set work_date = p_work_date,
      earned_days = p_earned_days,
      used_days = v_approved_used,
      remaining_days = p_earned_days - v_approved_used,
      site_id = p_site_id,
      note = nullif(trim(p_note), ''),
      updated_by_employee_id = public.current_employee_id()
  where id = p_record_id;
end;
$$;

create or replace function public.cancel_holiday_work(
  p_record_id bigint,
  p_comment text default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_record public.holiday_work_records%rowtype;
  v_committed_allocated numeric(6,2);
begin
  if not public.is_application_admin() then raise exception 'admin_required'; end if;

  select * into v_record from public.holiday_work_records
  where id = p_record_id for update;
  if not found then raise exception 'holiday_work_record_not_found'; end if;
  if v_record.status = 'cancelled' then return; end if;

  select coalesce(sum(ca.allocated_days), 0) into v_committed_allocated
  from public.comp_leave_allocations ca
  join public.applications a on a.id = ca.application_id
  where ca.holiday_work_record_id = p_record_id
    and a.status in ('submitted', 'approved');

  if v_committed_allocated > 0 then
    raise exception 'holiday_work_allocated_to_submitted_or_approved_application_cannot_cancel';
  end if;

  update public.holiday_work_records
  set status = 'cancelled',
      used_days = 0,
      remaining_days = earned_days,
      note = case when nullif(trim(p_comment), '') is null then note
        else concat_ws(E'\n', note, '取消理由: ' || trim(p_comment)) end,
      updated_by_employee_id = public.current_employee_id()
  where id = p_record_id;
end;
$$;

