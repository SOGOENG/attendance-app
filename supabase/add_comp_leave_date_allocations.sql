-- Internal only. Defines a NEW policy at submission, not a reconstruction of history:
-- usage dates ascending, then selected sources FIFO (work_date, id). Source totals
-- are fixed by the existing allocation table; no change to balance/approval logic.
create or replace function public.rebuild_comp_leave_date_allocations_internal(p_application_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
declare
  v_date record; v_source record; v_need numeric; v_take numeric;
  v_days numeric; v_allocated numeric;
begin
  perform 1 from public.applications where id=p_application_id for update;
  perform 1 from public.comp_leave_dates where application_id=p_application_id order by id for update;
  perform 1 from public.comp_leave_allocations where application_id=p_application_id order by id for update;
  select coalesce(sum(days),0) into v_days from public.comp_leave_dates where application_id=p_application_id;
  select coalesce(sum(allocated_days),0) into v_allocated from public.comp_leave_allocations where application_id=p_application_id;
  if v_days<=0 or v_days<>v_allocated then raise exception 'comp_leave_date_allocation_mismatch'; end if;
  delete from public.comp_leave_date_allocations where application_id=p_application_id;
  for v_date in select * from public.comp_leave_dates where application_id=p_application_id order by leave_date,id
  loop
    v_need:=v_date.days;
    for v_source in
      select ca.id,ca.holiday_work_record_id,ca.allocated_days-coalesce((
        select sum(da.allocated_days) from public.comp_leave_date_allocations da
        where da.comp_leave_allocation_id=ca.id),0) as available
      from public.comp_leave_allocations ca
      join public.holiday_work_records h on h.id=ca.holiday_work_record_id
      where ca.application_id=p_application_id order by h.work_date,h.id,ca.id
    loop
      exit when v_need=0;
      v_take:=least(v_need,v_source.available);
      if v_take<=0 then continue; end if;
      insert into public.comp_leave_date_allocations
        (application_id,comp_leave_date_id,comp_leave_allocation_id,holiday_work_record_id,allocated_days,created_by_employee_id)
      values(p_application_id,v_date.id,v_source.id,v_source.holiday_work_record_id,v_take,public.current_employee_id());
      v_need:=v_need-v_take;
    end loop;
    if v_need<>0 then raise exception 'comp_leave_date_allocation_mismatch'; end if;
  end loop;
  update public.comp_leave_application_details set date_allocations_recorded=true where application_id=p_application_id;
end;
$$;

create or replace function public.sync_comp_leave_date_allocations_status()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.application_type<>'comp_leave' then return new; end if;
  if new.status='submitted' and old.status is distinct from new.status then
    perform public.rebuild_comp_leave_date_allocations_internal(new.id);
  elsif new.status in ('draft','revision_required','rejected','cancelled') then
    delete from public.comp_leave_date_allocations where application_id=new.id;
    update public.comp_leave_application_details set date_allocations_recorded=false where application_id=new.id;
  end if;
  return new;
end;
$$;
drop trigger if exists comp_leave_date_allocations_status on public.applications;
create trigger comp_leave_date_allocations_status after update of status on public.applications
  for each row execute function public.sync_comp_leave_date_allocations_status();

-- Direct-registration RPCs insert their audit event AFTER dates and allocations
-- have been finalized. Both registration and edit are in that same transaction.
create or replace function public.sync_admin_comp_leave_date_allocations_history()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.to_status='approved' and (new.from_status is null or new.from_status='approved')
    and exists(select 1 from public.applications a where a.id=new.application_id
      and a.application_type='comp_leave' and a.status='approved'
      and pg_catalog.starts_with(coalesce(a.reviewer_comment,''),'admin_comp_usage:'))
    and (select count(*) from public.comp_leave_dates where application_id=new.application_id)=1
    and exists(select 1 from public.comp_leave_dates where application_id=new.application_id and admin_direct) then
    perform public.rebuild_comp_leave_date_allocations_internal(new.application_id);
  end if;
  return new;
end;
$$;
drop trigger if exists comp_leave_date_allocations_admin_history on public.application_status_history;
create trigger comp_leave_date_allocations_admin_history after insert on public.application_status_history
  for each row execute function public.sync_admin_comp_leave_date_allocations_history();

-- Fail closed independently of the audit INSERT. Only new direct registrations
-- and actual changes to their source rows opt in; untouched legacy rows remain
-- unrecorded. If the audit hook is omitted/skipped, the deferred check rejects
-- the transaction instead of committing usage without its daily mapping.
create or replace function public.require_admin_comp_leave_date_allocations()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_app bigint; v_direct boolean := false;
begin
  v_app:=coalesce(new.application_id,old.application_id);
  if tg_table_name='comp_leave_dates' then
    v_direct:=coalesce(new.admin_direct,false) or coalesce(old.admin_direct,false);
  end if;
  if exists(select 1 from public.applications a where a.id=v_app
    and a.application_type='comp_leave' and a.status='approved'
    and (v_direct or pg_catalog.starts_with(coalesce(a.reviewer_comment,''),'admin_comp_usage:')
      or exists(select 1 from public.comp_leave_dates d where d.application_id=a.id and d.admin_direct))) then
    if tg_table_name='comp_leave_application_details' then
      new.date_allocations_recorded:=true;
    else
      update public.comp_leave_application_details set date_allocations_recorded=true where application_id=v_app;
    end if;
  end if;
  if tg_op='DELETE' then return old; end if;
  return new;
end;
$$;
drop trigger if exists comp_leave_date_allocations_required on public.comp_leave_application_details;
create trigger comp_leave_date_allocations_required before insert on public.comp_leave_application_details
  for each row execute function public.require_admin_comp_leave_date_allocations();
drop trigger if exists comp_leave_date_allocations_required on public.comp_leave_dates;
create trigger comp_leave_date_allocations_required before insert or update or delete on public.comp_leave_dates
  for each row execute function public.require_admin_comp_leave_date_allocations();
drop trigger if exists comp_leave_date_allocations_required on public.comp_leave_allocations;
create trigger comp_leave_date_allocations_required before insert or update or delete on public.comp_leave_allocations
  for each row execute function public.require_admin_comp_leave_date_allocations();

-- Deferred checks see the final transaction state, allowing direct edits to
-- delete/recreate allocations first, but rejecting any committed partial mapping.
create or replace function public.check_comp_leave_date_allocations_internal()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_app bigint; v_recorded boolean; v_status text;
begin
  if tg_table_name='applications' then v_app:=coalesce(new.id,old.id);
  else v_app:=coalesce(new.application_id,old.application_id); end if;
  select d.date_allocations_recorded,a.status into v_recorded,v_status
    from public.comp_leave_application_details d join public.applications a on a.id=d.application_id
    where d.application_id=v_app;
  if not found then return null; end if;
  if not v_recorded then
    if exists(select 1 from public.comp_leave_date_allocations where application_id=v_app) then
      raise exception 'comp_leave_date_allocation_unrecorded';
    end if;
    return null;
  end if;
  if v_status not in ('submitted','approved') or
    not exists(select 1 from public.comp_leave_dates where application_id=v_app) or
    exists(select 1 from public.comp_leave_dates d where d.application_id=v_app and d.days<>(
      select coalesce(sum(da.allocated_days),0) from public.comp_leave_date_allocations da where da.comp_leave_date_id=d.id)) or
    exists(select 1 from public.comp_leave_allocations ca where ca.application_id=v_app and ca.allocated_days<>(
      select coalesce(sum(da.allocated_days),0) from public.comp_leave_date_allocations da where da.comp_leave_allocation_id=ca.id)) then
    raise exception 'comp_leave_date_allocation_mismatch';
  end if;
  return null;
end;
$$;
do $$
declare v_table text;
begin
  foreach v_table in array array['applications','comp_leave_application_details','comp_leave_dates','comp_leave_allocations','comp_leave_date_allocations'] loop
    execute format('drop trigger if exists comp_leave_date_allocations_check on public.%I',v_table);
    execute format('create constraint trigger comp_leave_date_allocations_check after insert or update or delete on public.%I deferrable initially deferred for each row execute function public.check_comp_leave_date_allocations_internal()',v_table);
  end loop;
end;
$$;

